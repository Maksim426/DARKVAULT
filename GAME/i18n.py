def get_lang():
    return GAME_SETTINGS.get("language", "ru")


def tr(key, default=None):
    lang = get_lang()
    bucket = TEXTS.get(lang, TEXTS["ru"])
    if key in bucket:
        return bucket[key]
    if default is not None:
        return default
    return TEXTS["ru"].get(key, key)


def tr_mode(mode_key):
    lang = get_lang()
    modes = TEXTS.get(lang, TEXTS["ru"])["mode_names"]
    return modes.get(mode_key, mode_key)


def tr_mode_desc(mode_key):
    lang = get_lang()
    descs = TEXTS.get(lang, TEXTS["ru"])["mode_descs"]
    return descs.get(mode_key, "")


def tr_boss(boss_key):
    lang = get_lang()
    names = TEXTS.get(lang, TEXTS["ru"])["boss_names"]
    if boss_key in names:
        return names[boss_key]
    return boss_key.replace("_", " ").upper()


def tr_boss_subtitle(boss_key):
    lang = get_lang()
    subs = TEXTS.get(lang, TEXTS["ru"])["boss_subtitles"]
    if boss_key in subs:
        return subs[boss_key]
    return "СТРАЖ ПОДЗЕМЕЛИЙ" if lang == "ru" else "GUARDIAN OF THE DEPTHS"


def tr_floor(level):
    lang = get_lang()
    floors = TEXTS.get(lang, TEXTS["ru"])["floor_names"]
    if level in floors:
        return floors[level]
    if lang == "ru":
        return f"БЕСКОНЕЧНАЯ БЕЗДНА · ГЛУБИНА {level}"
    return f"ENDLESS ABYSS · DEPTH {level}"


def tr_room(room_type):
    lang = get_lang()
    rooms = TEXTS.get(lang, TEXTS["ru"])["room_names"]
    return rooms.get(room_type, room_type.upper())
