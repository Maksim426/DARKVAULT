STARTER_HERO_IDS = tuple(h["id"] for h in HERO_ROSTER if h.get("starter"))


def get_hero(hero_id):
    for h in HERO_ROSTER:
        if h["id"] == hero_id:
            return h
    return HERO_ROSTER[0]


def _extract_stats_and_ach(acc_or_stats):
    if isinstance(acc_or_stats, dict):
        if "stats" in acc_or_stats:
            return acc_or_stats.get("stats") or {}, acc_or_stats.get("achievements") or {}
        return acc_or_stats, {}
    return {}, {}


def get_hero_unlock_progress(hero_id, acc_or_stats):
    h = get_hero(hero_id)
    if h.get("id") != hero_id or h.get("starter", True):
        return True, 1, 1
    unlock = h.get("unlock")
    if not isinstance(unlock, dict):
        return True, 1, 1
    stats, _ = _extract_stats_and_ach(acc_or_stats)
    stat_key = unlock.get("stat", "")
    target = max(1, int(unlock.get("target", 1)))
    val = stats.get(stat_key, 0)
    if isinstance(val, list):
        cur = len(val)
    elif isinstance(val, dict):
        cur = sum(1 for v in val.values() if v)
    elif isinstance(val, bool):
        cur = 1 if val else 0
    else:
        cur = int(val or 0)
    return cur >= target, min(cur, target), target


def is_hero_unlocked(hero_id, acc_or_stats):
    unlocked, _, _ = get_hero_unlock_progress(hero_id, acc_or_stats)
    return unlocked


def get_hero_unlock_text(hero_id, lang="ru"):
    h = get_hero(hero_id)
    if h.get("starter", True):
        return ""
    if lang == "en":
        return h.get("unlock_en", "")
    return h.get("unlock_ru", "")


def count_unlocked_heroes(acc_or_stats):
    return sum(1 for h in HERO_ROSTER if is_hero_unlocked(h["id"], acc_or_stats))
